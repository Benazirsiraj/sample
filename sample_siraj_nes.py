def add_four_numbers(a, b, c, d):
    """
    Function to add four numbers.
    
    Args:
        a (int or float): First number
        b (int or float): Second number  
        c (int or float): Third number
        d (int or float): Fourth number
        
    Returns:
        int or float: Sum of the four numbers
    """
    return a + b + c + d

# Example usage
if __name__ == "__main__":
    result = add_four_numbers(1, 2, 3, 4)
    print(f"The sum of 1, 2, 3, and 4 is: {result}")
